/// A safe zone: a centre point + radius, set per GPS Tracker.
class Geofence {
  final double centerLat;
  final double centerLng;
  final String addressLabel;
  final double radiusMeters;

  const Geofence({
    required this.centerLat,
    required this.centerLng,
    required this.addressLabel,
    required this.radiusMeters,
  });

  /// A zone at (0,0) is what an unset placeholder looks like; the firmware
  /// ignores it too.
  bool get isValid =>
      centerLat >= -90 &&
      centerLat <= 90 &&
      centerLng >= -180 &&
      centerLng <= 180 &&
      !(centerLat == 0 && centerLng == 0) &&
      radiusMeters > 0;

  Map<String, dynamic> toJson() => {
        'centerLat': centerLat,
        'centerLng': centerLng,
        'addressLabel': addressLabel,
        'radiusMeters': radiusMeters,
      };

  static Geofence? tryFromJson(Object? value) {
    final json = parseMap(value);
    if (json == null) return null;
    final lat = parseDouble(json['centerLat']);
    final lng = parseDouble(json['centerLng']);
    final radius = parseDouble(json['radiusMeters']);
    if (lat == null || lng == null || radius == null) return null;
    return Geofence(
      centerLat: lat,
      centerLng: lng,
      addressLabel: parseString(json['addressLabel']) ?? '',
      radiusMeters: radius,
    );
  }

  Geofence copyWith({
    double? centerLat,
    double? centerLng,
    String? addressLabel,
    double? radiusMeters,
  }) {
    return Geofence(
      centerLat: centerLat ?? this.centerLat,
      centerLng: centerLng ?? this.centerLng,
      addressLabel: addressLabel ?? this.addressLabel,
      radiusMeters: radiusMeters ?? this.radiusMeters,
    );
  }
}

/// Where a tracker is relative to its safe zone, as reported by firmware.
enum GeofenceStatus { inside, outside, unknown }

/// How the app should present a device's connection right now.
enum DeviceConnectivity {
  /// The device has never reported.
  neverSeen,

  /// GPS Tracker: recent update. Alarm Button: recent quiet check-in.
  online,

  /// GPS Tracker: no update for a while. Alarm Button: check-in overdue.
  offline,
}

/// A registered device (GPS Tracking Chip or Alarm Button). Every device is
/// self-contained: its own UUID, name, contacts and (for trackers) safe zone.
///
/// Field ownership in Firestore:
///  - app: id, type, name, contacts, geofence
///  - firmware: lastSeen, lastLat, lastLng, isOnline, alarmActive,
///    geofenceStatus, charging, fwVersion, deviceUid
class Device {
  final String id; // UUID generated by the device firmware on first boot
  final DeviceType type;
  String name;
  final List<EmergencyContact> contacts;
  Geofence? geofence;
  DateTime? lastSeen;
  double? lastLat;
  double? lastLng;
  bool isOnline;
  bool alarmActive;
  GeofenceStatus geofenceStatus;
  bool charging;
  String? fwVersion;
  String? deviceUid;

  Device({
    required this.id,
    required this.type,
    required this.name,
    List<EmergencyContact>? contacts,
    this.geofence,
    this.lastSeen,
    this.lastLat,
    this.lastLng,
    this.isOnline = false,
    this.alarmActive = false,
    this.geofenceStatus = GeofenceStatus.unknown,
    this.charging = false,
    this.fwVersion,
    this.deviceUid,
  }) : contacts = contacts ?? [];

  /// A device document created by firmware has no name until someone adds
  /// it in the app.
  bool get isClaimed => name.trim().isNotEmpty;

  bool get hasLocation => lastLat != null && lastLng != null;

  DeviceConnectivity connectivityAt(DateTime now) {
    final seen = lastSeen;
    if (seen == null) return DeviceConnectivity.neverSeen;
    final limit = type == DeviceType.gpsTracker
        ? AppConstants.gpsTrackerOfflineAfter
        : AppConstants.alarmCheckInOverdueAfter;
    return now.difference(seen) <= limit ? DeviceConnectivity.online : DeviceConnectivity.offline;
  }

  /// Emails of this device's emergency contacts, normalised.
  Set<String> get contactEmails =>
      contacts.map((c) => normalizeEmail(c.email)).where((e) => e.isNotEmpty).toSet();

  Map<String, dynamic> toJson() => {
        'id': id,
        'type': type.name,
        'name': name,
        'contacts': contacts.map((c) => c.toJson()).toList(),
        'geofence': geofence?.toJson(),
        'lastSeen': lastSeen?.toIso8601String(),
        'lastLat': lastLat,
        'lastLng': lastLng,
        'isOnline': isOnline,
        'alarmActive': alarmActive,
        'geofenceStatus': geofenceStatus.name,
        'charging': charging,
        'fwVersion': fwVersion,
        'deviceUid': deviceUid,
      };

  /// Throws [FormatException] only when the id or type is unusable.
  factory Device.fromJson(Map<String, dynamic> json, {String? fallbackId}) {
    final id = parseString(json['id']) ?? fallbackId;
    if (id == null || id.isEmpty) {
      throw const FormatException('Device without id');
    }
    final typeName = parseString(json['type']);
    final type = DeviceType.values.where((t) => t.name == typeName).firstOrNull;
    if (type == null) {
      throw FormatException('Device $id has unknown type "$typeName"');
    }
    final contacts = (json['contacts'] is List ? json['contacts'] as List : const [])
        .map(EmergencyContact.tryFromJson)
        .whereType<EmergencyContact>()
        .toList();

    return Device(
      id: id,
      type: type,
      name: parseString(json['name']) ?? '',
      contacts: contacts,
      geofence: Geofence.tryFromJson(json['geofence']),
      lastSeen: parseDateTime(json['lastSeen']),
      lastLat: parseDouble(json['lastLat']),
      lastLng: parseDouble(json['lastLng']),
      isOnline: parseBool(json['isOnline']),
      alarmActive: parseBool(json['alarmActive']),
      geofenceStatus: GeofenceStatus.values
              .where((s) => s.name == parseString(json['geofenceStatus']))
              .firstOrNull ??
          GeofenceStatus.unknown,
      charging: parseBool(json['charging']),
      fwVersion: parseString(json['fwVersion']),
      deviceUid: parseString(json['deviceUid']),
    );
  }
}

/// An emergency contact. Contacts are Grizzly users: the email is the one
/// they sign in with, which is how their phone knows to alert them.
class EmergencyContact {
  final String id;
  String name;
  String email;
  String phone;

  EmergencyContact({
    required this.id,
    required this.name,
    required this.email,
    this.phone = '',
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'name': name,
        'email': email,
        'phone': phone,
      };

  static EmergencyContact? tryFromJson(Object? value) {
    final json = parseMap(value);
    final id = json == null ? null : parseString(json['id']);
    if (json == null || id == null) return null;

    var email = parseString(json['email']) ?? '';
    var phone = parseString(json['phone']) ?? '';
    // Older app versions stored a single "phoneOrEmail" field.
    final legacy = parseString(json['phoneOrEmail']);
    if (legacy != null && email.isEmpty && phone.isEmpty) {
      if (legacy.contains('@')) {
        email = legacy;
      } else {
        phone = legacy;
      }
    }
    return EmergencyContact(
      id: id,
      name: parseString(json['name']) ?? '',
      email: email,
      phone: phone,
    );
  }
}
